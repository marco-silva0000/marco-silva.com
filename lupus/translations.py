def get_localized_role(role_id: str, default_info: dict[str, Any], lang: Optional[str] = "en") -> dict[str, Any]:
    """Return localized role metadata while preserving base properties (id, faction, emoji)."""
    if not lang or lang not in SUPPORTED_LANGUAGES or lang == "en":
        return default_info

    lang_data = ROLE_TRANSLATIONS.get(role_id, {}).get(lang)
    if not lang_data:
        return default_info

    localized = dict(default_info)
    localized["name"] = lang_data.get("name", default_info.get("name"))
    localized["description"] = lang_data.get("description", default_info.get("description"))

    guide = dict(default_info.get("guide", {}))
    if "objective" in lang_data:
        guide["objective"] = lang_data["objective"]
    if "day_tips" in lang_data:
        guide["day_tips"] = lang_data["day_tips"]
    if "night_tips" in lang_data:
        guide["night_tips"] = lang_data["night_tips"]
    if "pro_tip" in lang_data:
        guide["pro_tip"] = lang_data["pro_tip"]

    localized["guide"] = guide
    return localized


