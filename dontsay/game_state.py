"""Redis-backed game state engine for 'Don't Say the Same Thing as Me'.

Mechanics:
- Players are given a prompt generated by the linguistic prompt engine.
- Players secretly submit their answer before the timer expires.
- Zero-spoiler guarantee: other players' answers are never sent over the wire until reveal!
- When revealed, identical answers clash (0 points or penalty).
- Unique valid answers score points (+100, +50 obscurity bonus).
- Host can arbitrate / override validity; AI automatically evaluates unknown answers.
"""

import copy
import json
import os
import time
import uuid
from typing import Any, Optional

import redis

from gamerooms.language_support import normalize_language_code
from gamerooms.prompt_engine import (
    PACK_CHOICES,
    clean_answer_key,
    get_next_prompt,
    validate_player_answer,
)
from gamerooms.prompt_engine.evaluator import are_similar_answers, cluster_answer_keys
from website.version import VERSION_COUNTER

_redis = None
_fallback_store: dict[str, str] = {}

COLLISION_MODES = (
    "classic",  # Clashes get 0 points, unique gets 100 points
    "harsh",  # Clashes lose 50 points (-50), unique gets 100 points
)

PACING_MODES = (
    "funnel",  # Wide -> narrow -> sudden death
    "narrow",  # High-collision narrow only
    "random",  # Pure random mix
)

GAME_MODES = (
    ("classic", "Standard (Secret Anti-Clash)"),
    ("the_me", "The ME (Genius Host: Don't Say What I Say)"),
    ("oral_table", "Oral Table (Living Room: Say Out Loud)"),
)

THE_ME_ROTATIONS = (
    ("rotate", "Rotate Each Round"),
    ("host_fixed", "Host is Always 'The ME'"),
)

DEFAULT_SETTINGS: dict[str, Any] = {
    "game_mode": "classic",  # "classic", "the_me", "oral_table"
    "the_me_rotation": "rotate",  # "rotate", "host_fixed"
    "pack": "mix",  # "mix", "geo", "media", "food", "nature", "history", "weird"
    "max_rounds": 6,  # 0 = infinite / until 1 survivor or host ends
    "round_timer": 45,  # 30, 45, 60, 0 (untimed)
    "collision_mode": "classic",
    "pacing_mode": "funnel",
    "fuzzy_clash": True,
    "ai_validation": True,
    "obscurity_bonus": True,
    "allow_generative_prompts": True,
}


def get_redis_client():
    global _redis
    if _redis is None:
        redis_url = os.environ.get("REDIS_URL", "redis://localhost:6379/0")
        try:
            r = redis.from_url(redis_url, socket_connect_timeout=1.5, socket_timeout=1.5)
            r.ping()
            _redis = r
        except Exception:
            _redis = False
    return _redis if _redis is not False else None


def get_game(code: str) -> dict[str, Any]:
    code = code.upper()
    r = get_redis_client()
    raw = None
    if r:
        try:
            raw = r.get(f"dontsay:{code}")
        except Exception:
            raw = None
    if raw is None:
        raw = _fallback_store.get(f"dontsay:{code}")

    if raw:
        try:
            data = json.loads(raw if isinstance(raw, str) else raw.decode())
            data.setdefault("version_counter", VERSION_COUNTER)
            return data
        except Exception:
            pass

    return create_game(code)


def save_game(code: str, state: dict[str, Any]) -> None:
    code = code.upper()
    state["updated_at"] = time.time()
    state["version_counter"] = VERSION_COUNTER
    raw = json.dumps(state)
    r = get_redis_client()
    if r:
        try:
            r.set(f"dontsay:{code}", raw, ex=86400 * 3)
        except Exception:
            pass
    _fallback_store[f"dontsay:{code}"] = raw


def create_game(code: str, title: str = "", password: str = "", language: str = "en") -> dict[str, Any]:
    code = code.upper()
    norm_lang = normalize_language_code(language)
    state: dict[str, Any] = {
        "code": code,
        "title": title or f"Don't Say Room {code}",
        "password": password,
        "language": norm_lang,
        "creator": None,
        "creator_id": None,
        "phase": "lobby",  # "lobby", "answering", "reveal", "recap", "gameover"
        "round_num": 0,
        "settings": copy.deepcopy(DEFAULT_SETTINGS),
        "players": {},
        "next_player_seq": 1,
        "current_prompt": None,
        "used_prompt_ids": [],
        "round_answers": {},  # {pid: {"raw": str, "submitted_at": float}}
        "round_results": None,  # Computed collision results and scores for current round
        "the_me_player_id": None,  # Player ID of "The ME" in genius host mode
        "the_me_answer": None,  # Secret answer locked by "The ME"
        "round_timer_started_at": None,
        "round_timer_duration": 45,
        "round_history": [],
        "activity_log": [],
        "version_counter": VERSION_COUNTER,
        "created_at": time.time(),
        "updated_at": time.time(),
    }
    save_game(code, state)
    return state


def append_event(state: dict[str, Any], author: str, text: str) -> None:
    events = state.setdefault("activity_log", [])
    events.append(
        {
            "id": uuid.uuid4().hex[:8],
            "author": author,
            "text": text,
            "timestamp": time.time(),
        }
    )
    if len(events) > 60:
        state["activity_log"] = events[-60:]


def find_player_by_token(state: dict[str, Any], token: Optional[str]) -> Optional[dict[str, Any]]:
    if not token:
        return None
    for p in state.get("players", {}).values():
        if p.get("token") == token:
            return p
    return None


def find_player_by_name(state: dict[str, Any], name: Optional[str]) -> Optional[dict[str, Any]]:
    if not name:
        return None
    lowered = name.strip().lower()
    for p in state.get("players", {}).values():
        if p.get("name", "").strip().lower() == lowered:
            return p
    return None


def _unique_name(state: dict[str, Any], raw_name: str, exclude_pid: Optional[str] = None) -> str:
    base = (raw_name or "Player").strip()[:28] or "Player"
    existing = {p["name"].lower() for pid, p in state.get("players", {}).items() if pid != exclude_pid}
    if base.lower() not in existing:
        return base
    i = 2
    while f"{base} {i}".lower() in existing:
        i += 1
    return f"{base} {i}"


def add_player(
    state: dict[str, Any],
    name: str,
    token: Optional[str] = None,
    is_admin: bool = False,
    channel_name: str = "",
) -> tuple[dict[str, Any], dict[str, Any], bool]:
    """Add or reconnect a player cleanly; first joiner becomes host if unset."""
    existing = find_player_by_token(state, token)
    if existing:
        existing["connected"] = True
        if channel_name:
            existing["channel_name"] = channel_name
        if is_admin:
            existing["is_admin"] = True
        save_game(state["code"], state)
        return state, existing, False

    by_name = find_player_by_name(state, name)
    if by_name:
        is_host_reconnect = is_admin and (by_name.get("is_admin") or by_name.get("id") == state.get("creator_id"))
        if is_host_reconnect or not by_name.get("connected", False) or state.get("phase") in ("lobby", "waiting", None):
            by_name["connected"] = True
            if channel_name:
                by_name["channel_name"] = channel_name
            if is_admin:
                by_name["is_admin"] = True
            save_game(state["code"], state)
            return state, by_name, False

    seq = state.get("next_player_seq", 1)
    pid = f"p{seq}"
    state["next_player_seq"] = seq + 1

    clean_name = _unique_name(state, name)
    has_any_admin = any(p.get("is_admin") for p in state.get("players", {}).values())
    grant_admin = bool(is_admin or not has_any_admin)

    player = {
        "id": pid,
        "name": clean_name,
        "token": token or uuid.uuid4().hex[:20],
        "score": 0,
        "is_admin": grant_admin,
        "is_spectator": False,
        "connected": True,
        "channel_name": channel_name or None,
    }
    state.setdefault("players", {})[pid] = player

    if grant_admin and not state.get("creator_id"):
        state["creator_id"] = pid
        state["creator"] = clean_name

    append_event(state, "System", f"👋 {clean_name} joined the room.")
    save_game(state["code"], state)
    return state, player, True


def is_player_admin(state: dict[str, Any], player: Optional[dict[str, Any]]) -> bool:
    if not player:
        return False
    return bool(player.get("is_admin") or player.get("id") == state.get("creator_id"))


def active_players(state: dict[str, Any]) -> list[dict[str, Any]]:
    return [p for p in state.get("players", {}).values() if not p.get("is_spectator")]


def toggle_spectator(state: dict[str, Any], player_id: str) -> bool:
    p = state.get("players", {}).get(player_id)
    if not p:
        return False
    p["is_spectator"] = not p.get("is_spectator", False)
    mode_str = "Spectator 👀" if p["is_spectator"] else "Active Player 🎮"
    append_event(state, "System", f"{p['name']} is now {mode_str}.")
    save_game(state["code"], state)
    return True


def kick_player(state: dict[str, Any], target_id: str, by_name: str = "Host") -> Optional[dict[str, Any]]:
    players = state.get("players", {})
    if target_id not in players:
        return None
    kicked = players.pop(target_id)
    append_event(state, "System", f"🚪 {kicked.get('name')} was removed by {by_name}.")
    save_game(state["code"], state)
    return kicked


def transfer_host(state: dict[str, Any], target_id: str) -> bool:
    """Transfer room creator / host role to another player."""
    target = state.get("players", {}).get(target_id)
    if not target:
        return False
    target["is_admin"] = True
    state["creator_id"] = target_id
    state["creator"] = target["name"]
    append_event(state, "System", f"👑 Room Host privileges transferred to {target['name']}.")
    save_game(state["code"], state)
    return True


def update_settings(state: dict[str, Any], new_settings: dict[str, Any]) -> None:
    cur = state.setdefault("settings", copy.deepcopy(DEFAULT_SETTINGS))
    if "game_mode" in new_settings and new_settings["game_mode"] in dict(GAME_MODES):
        cur["game_mode"] = str(new_settings["game_mode"])
    if "the_me_rotation" in new_settings and new_settings["the_me_rotation"] in dict(THE_ME_ROTATIONS):
        cur["the_me_rotation"] = str(new_settings["the_me_rotation"])
    if "pack" in new_settings:
        cur["pack"] = str(new_settings["pack"])
    if "max_rounds" in new_settings:
        try:
            cur["max_rounds"] = max(0, min(30, int(new_settings["max_rounds"])))
        except (ValueError, TypeError):
            pass
    if "round_timer" in new_settings:
        try:
            cur["round_timer"] = max(0, min(180, int(new_settings["round_timer"])))
        except (ValueError, TypeError):
            pass
    if "collision_mode" in new_settings and new_settings["collision_mode"] in COLLISION_MODES:
        cur["collision_mode"] = new_settings["collision_mode"]
    if "pacing_mode" in new_settings and new_settings["pacing_mode"] in PACING_MODES:
        cur["pacing_mode"] = new_settings["pacing_mode"]
    if "fuzzy_clash" in new_settings:
        cur["fuzzy_clash"] = bool(new_settings["fuzzy_clash"])
    if "ai_validation" in new_settings:
        cur["ai_validation"] = bool(new_settings["ai_validation"])
    if "obscurity_bonus" in new_settings:
        cur["obscurity_bonus"] = bool(new_settings["obscurity_bonus"])
    save_game(state["code"], state)


def start_game(state: dict[str, Any]) -> bool:
    """Start game or advance to round 1 from lobby."""
    state["round_num"] = 1
    state["round_history"] = []
    state["used_prompt_ids"] = []
    state["the_me_gameover"] = False
    state["the_me_winner"] = None
    state["winner_reason"] = None
    state["winner_id"] = None
    for p in state.get("players", {}).values():
        p["score"] = 0
        p["eliminated"] = False
        p.pop("eliminated_round", None)

    return setup_round(state)


def setup_round(state: dict[str, Any]) -> bool:
    """Prepare a fresh round: choose prompt and configure mode phase."""
    settings = state.get("settings", DEFAULT_SETTINGS)
    pack = settings.get("pack", "mix")
    game_mode = settings.get("game_mode", "classic")
    allow_gen = settings.get("allow_generative_prompts", True)
    used_ids = set(state.get("used_prompt_ids", []))

    prompt = get_next_prompt(
        pack=pack,
        language=state.get("language", "en"),
        used_ids=used_ids,
        allow_generative=allow_gen,
        round_num=state.get("round_num", 1),
        pacing_mode=settings.get("pacing_mode", "funnel"),
    )
    state["current_prompt"] = prompt
    state.setdefault("used_prompt_ids", []).append(prompt.get("id"))
    state["round_answers"] = {}
    state["round_results"] = None
    state["the_me_answer"] = None

    prompt_display = prompt.get("display_text") or prompt.get("text")
    append_event(state, "System", f'🎯 Round {state["round_num"]}: "{prompt_display}"')

    if game_mode == "the_me":
        # Select "The ME" player from alive, non-eliminated players
        actives = [p["id"] for p in active_players(state) if p.get("connected") and not p.get("eliminated")]
        if not actives:
            actives = [p["id"] for p in active_players(state) if not p.get("eliminated")] or list(
                state.get("players", {}).keys()
            )

        if settings.get("the_me_rotation") == "host_fixed" and state.get("creator_id") in state.get("players", {}):
            the_me_id = state.get("creator_id")
        else:
            idx = (state.get("round_num", 1) - 1) % max(1, len(actives))
            the_me_id = actives[idx] if actives else None

        state["the_me_player_id"] = the_me_id
        state["phase"] = "the_me_answering"
        the_me_p = state.get("players", {}).get(the_me_id)
        the_me_name = the_me_p["name"] if the_me_p else "The ME"
        append_event(state, "System", f"👑 {the_me_name} is 'The ME'! Setting secret forbidden word...")
        state["round_timer_duration"] = 0
        state["round_timer_started_at"] = None

    elif game_mode == "oral_table":
        state["phase"] = "oral_speaking"
        state["round_timer_duration"] = 0
        state["round_timer_started_at"] = None
        append_event(state, "System", "🗣️ Living Room Oral Round! Read the prompt aloud.")

    else:  # "classic"
        timer_dur = int(settings.get("round_timer", 45))
        state["round_timer_duration"] = timer_dur
        state["round_timer_started_at"] = time.time() if timer_dur > 0 else None
        state["phase"] = "answering"

    save_game(state["code"], state)
    return True


def submit_the_me_answer(state: dict[str, Any], player_id: str, answer_text: str) -> bool:
    """Designated 'The ME' player locks in the forbidden word for the round."""
    if state.get("phase") != "the_me_answering":
        return False
    if player_id != state.get("the_me_player_id"):
        return False
    cleaned = (answer_text or "").strip()[:80]
    if not cleaned:
        return False

    state["the_me_answer"] = {
        "raw": cleaned,
        "clean_key": clean_answer_key(cleaned),
        "submitted_at": time.time(),
    }
    state.setdefault("round_answers", {})[player_id] = {
        "raw": cleaned,
        "submitted_at": time.time(),
    }

    # Transition to answering phase for all other players
    state["phase"] = "answering"
    timer_dur = int(state.get("settings", {}).get("round_timer", 45))
    state["round_timer_duration"] = timer_dur
    state["round_timer_started_at"] = time.time() if timer_dur > 0 else None

    the_me_p = state.get("players", {}).get(player_id)
    the_me_name = the_me_p["name"] if the_me_p else "The ME"
    append_event(state, "System", f"🔒 {the_me_name} locked in their secret word! Everyone else, answer now!")
    save_game(state["code"], state)
    return True


def submit_answer(state: dict[str, Any], player_id: str, answer_text: str) -> bool:
    """Record secret answer from a player during answering phase."""
    if state.get("phase") != "answering":
        return False
    player = state.get("players", {}).get(player_id)
    if not player or player.get("is_spectator") or player.get("eliminated"):
        return False

    game_mode = state.get("settings", {}).get("game_mode", "classic")
    the_me_id = state.get("the_me_player_id")
    if game_mode == "the_me" and player_id == the_me_id:
        return False

    cleaned = (answer_text or "").strip()[:80]
    state.setdefault("round_answers", {})[player_id] = {
        "raw": cleaned,
        "submitted_at": time.time(),
    }
    save_game(state["code"], state)

    # Check if all active connected players have submitted
    if game_mode == "the_me":
        actives = [p["id"] for p in active_players(state) if p.get("connected") and p["id"] != the_me_id]
    else:
        actives = [p["id"] for p in active_players(state) if p.get("connected")]

    submitted = set(state["round_answers"].keys())
    if actives and all(pid in submitted for pid in actives):
        evaluate_and_reveal_round(state)
        return True

    return True


def evaluate_and_reveal_round(state: dict[str, Any]) -> dict[str, Any]:
    """
    Reveal all submitted answers, detect clashes, evaluate validity, and compute scores.
    """
    if state.get("phase") in ("reveal", "recap") and state.get("round_results"):
        return state["round_results"]

    state["phase"] = "reveal"
    prompt = state.get("current_prompt") or {}
    prompt_text = prompt.get("display_text") or prompt.get("text", "")
    sample_answers = prompt.get("sample_answers", [])
    obscurity_examples = prompt.get("obscurity_examples", [])
    settings = state.get("settings", DEFAULT_SETTINGS)
    use_ai = bool(settings.get("ai_validation", True))
    allow_obs = bool(settings.get("obscurity_bonus", True))
    collision_mode = settings.get("collision_mode", "classic")

    answers = state.get("round_answers", {})
    players = state.get("players", {})

    # 1. Group by clean_answer_key with optional fuzzy clustering
    entries: list[tuple[str, str]] = []
    player_keys: dict[str, str] = {}

    for pid in players.keys():
        ans_info = answers.get(pid)
        raw_ans = ans_info.get("raw", "") if ans_info else ""
        ckey = clean_answer_key(raw_ans)
        player_keys[pid] = ckey
        if ckey:
            entries.append((ckey, pid))

    fuzzy_clash = bool(settings.get("fuzzy_clash", True))
    grouped_by_key: dict[str, list[str]] = cluster_answer_keys(entries, fuzzy=fuzzy_clash)

    # 2. Evaluate validity for each distinct non-empty key
    evaluated_keys: dict[str, dict[str, Any]] = {}
    for ckey, pids in grouped_by_key.items():
        sample_rep = answers[pids[0]]["raw"]
        val_res = validate_player_answer(
            prompt_text=prompt_text,
            answer=sample_rep,
            sample_answers=sample_answers,
            obscurity_examples=obscurity_examples,
            use_ai=use_ai,
        )
        evaluated_keys[ckey] = val_res

    # 3. Compute per-player scores and clash details
    player_results: dict[str, Any] = {}
    clash_groups: list[dict[str, Any]] = []

    game_mode = settings.get("game_mode", "classic")
    the_me_id = state.get("the_me_player_id") if game_mode == "the_me" else None
    the_me_raw = state.get("the_me_answer", {}).get("raw", "") if the_me_id else ""
    the_me_key = clean_answer_key(the_me_raw) if the_me_raw else ""
    me_victims = []

    if game_mode == "the_me" and the_me_id:
        # Evaluate guessers against 'The ME' (ELIMINATION MODE)
        # Regular players do NOT clash with each other in The ME mode.
        # Only matching The ME's secret word gets the player eliminated!
        for ckey, pids in grouped_by_key.items():
            val_info = evaluated_keys.get(ckey, {"valid": True, "is_obscure": False})
            is_valid = val_info.get("valid", True)
            is_obs = val_info.get("is_obscure", False) and allow_obs
            other_pids = [p for p in pids if p != the_me_id]

            is_caught_by_me = (ckey == the_me_key) or (
                fuzzy_clash and bool(the_me_key) and are_similar_answers(ckey, the_me_key)
            )

            if is_caught_by_me:
                # Players trapped by The ME get eliminated!
                for pid in other_pids:
                    me_victims.append(pid)
                    players[pid]["eliminated"] = True
                    players[pid]["eliminated_round"] = state.get("round_num", 1)
                    pts = -50 if collision_mode == "harsh" else 0
                    players[pid]["score"] = max(0, players[pid].get("score", 0) + pts)
                    player_results[pid] = {
                        "player_id": pid,
                        "player_name": players[pid]["name"],
                        "raw_answer": answers[pid]["raw"],
                        "clean_key": ckey,
                        "status": "caught_by_me",
                        "is_valid": is_valid,
                        "is_obscure": False,
                        "points_awarded": pts,
                        "total_score": players[pid]["score"],
                        "eliminated": True,
                        "reason": f"💀 ELIMINATED! Said the same word as The ME ({the_me_raw})!",
                    }
                if other_pids:
                    clash_groups.append(
                        {
                            "clean_key": ckey,
                            "player_ids": [the_me_id] + other_pids,
                            "player_names": [players[the_me_id]["name"]]
                            + [players[p]["name"] for p in other_pids if p in players],
                            "answer_text": the_me_raw,
                            "is_valid": is_valid,
                        }
                    )
            else:
                # In The ME mode, regular players NEVER clash with each other
                for pid in other_pids:
                    if not is_valid:
                        pts = 0
                        status = "invalid"
                        reason = val_info.get("reason", "Invalid answer")
                    else:
                        pts = 150 if is_obs else 100
                        status = "escaped_me"
                        reason = f"Safe! Avoided The ME's word ({the_me_raw})"

                    players[pid]["score"] = max(0, players[pid].get("score", 0) + pts)
                    player_results[pid] = {
                        "player_id": pid,
                        "player_name": players[pid]["name"],
                        "raw_answer": answers[pid]["raw"],
                        "clean_key": ckey,
                        "status": status,
                        "is_valid": is_valid,
                        "is_obscure": is_obs,
                        "points_awarded": pts,
                        "total_score": players[pid]["score"],
                        "eliminated": False,
                        "reason": reason,
                    }

        # Score 'The ME'
        if the_me_id in players:
            me_pts = len(me_victims) * 100
            if me_victims:
                me_status = "the_me_mastermind"
                reason = f'Eliminated {len(me_victims)} player(s) with "{the_me_raw}"!'
            else:
                me_status = "the_me_avoided"
                me_pts = 50  # Consolation points for setting the word
                reason = "All players avoided your forbidden word!"

            players[the_me_id]["score"] = max(0, players[the_me_id].get("score", 0) + me_pts)
            player_results[the_me_id] = {
                "player_id": the_me_id,
                "player_name": players[the_me_id]["name"],
                "raw_answer": the_me_raw,
                "clean_key": the_me_key,
                "status": me_status,
                "is_valid": True,
                "is_obscure": False,
                "points_awarded": me_pts,
                "total_score": players[the_me_id]["score"],
                "eliminated": False,
                "reason": reason,
            }

        # Check elimination victory conditions
        alive_guessers = [
            p
            for pid, p in players.items()
            if pid != the_me_id and not p.get("is_spectator") and not p.get("eliminated")
        ]
        total_guessers = [p for pid, p in players.items() if pid != the_me_id and not p.get("is_spectator")]
        cur_round = int(state.get("round_num", 1))
        max_rounds = int(settings.get("max_rounds", 6))

        if len(alive_guessers) == 0 and total_guessers:
            state["the_me_gameover"] = True
            state["the_me_winner"] = "the_me"
            state["winner_id"] = the_me_id
            me_name = players[the_me_id]["name"] if the_me_id in players else "The ME"
            state["winner_reason"] = f"👑 The ME ({me_name}) eliminated all players! Absolute victory!"
            append_event(state, "System", f"💀 ALL PLAYERS ELIMINATED! {me_name} WINS!")
        elif len(alive_guessers) == 1 and len(total_guessers) > 1:
            survivor = alive_guessers[0]
            state["the_me_gameover"] = True
            state["the_me_winner"] = "survivor"
            state["winner_id"] = survivor["id"]
            state["winner_reason"] = f"🏆 Sole Survivor! {survivor['name']} is the last player standing!"
            append_event(state, "System", f"🏆 SOLE SURVIVOR! {survivor['name']} outlasted everyone!")
        elif max_rounds > 0 and cur_round >= max_rounds:
            state["the_me_gameover"] = True
            state["the_me_winner"] = "survivors"
            survivor_names = ", ".join(p["name"] for p in alive_guessers)
            state["winner_reason"] = (
                f"🎉 Survivors Win! {survivor_names} survived all {max_rounds} rounds against The ME!"
            )
            append_event(state, "System", f"🎉 {len(alive_guessers)} survivor(s) completed all rounds!")

    else:
        # Standard anti-clash mode
        for ckey, pids in grouped_by_key.items():
            val_info = evaluated_keys.get(ckey, {"valid": True, "is_obscure": False})
            is_valid = val_info.get("valid", True)
            is_obs = val_info.get("is_obscure", False) and allow_obs
            is_clash = len(pids) > 1

            if is_clash:
                clash_names = [players[p]["name"] for p in pids if p in players]
                clash_groups.append(
                    {
                        "clean_key": ckey,
                        "player_ids": pids,
                        "player_names": clash_names,
                        "answer_text": answers[pids[0]]["raw"],
                        "is_valid": is_valid,
                    }
                )

            for pid in pids:
                if not is_valid:
                    pts = 0
                    status = "invalid"
                elif is_clash:
                    pts = -50 if collision_mode == "harsh" else 0
                    status = "clash"
                else:
                    pts = 150 if is_obs else 100
                    status = "unique"

                players[pid]["score"] = max(0, players[pid].get("score", 0) + pts)
                player_results[pid] = {
                    "player_id": pid,
                    "player_name": players[pid]["name"],
                    "raw_answer": answers[pid]["raw"],
                    "clean_key": ckey,
                    "status": status,
                    "is_valid": is_valid,
                    "is_obscure": is_obs,
                    "points_awarded": pts,
                    "total_score": players[pid]["score"],
                    "reason": val_info.get("reason", ""),
                }

    # Handle players who did not submit an answer
    for pid, p in players.items():
        if pid not in player_results:
            is_elim = bool(p.get("eliminated"))
            player_results[pid] = {
                "player_id": pid,
                "player_name": p["name"],
                "raw_answer": "",
                "clean_key": "",
                "status": "eliminated" if is_elim else "no_answer",
                "is_valid": False,
                "is_obscure": False,
                "points_awarded": 0,
                "total_score": p.get("score", 0),
                "eliminated": is_elim,
                "reason": (
                    f"Eliminated in round {p.get('eliminated_round', 1)} (Spectating)"
                    if is_elim
                    else "Did not submit answer"
                ),
            }

    round_summary = {
        "round_num": state.get("round_num", 1),
        "prompt": prompt,
        "player_results": player_results,
        "clash_groups": clash_groups,
        "total_submissions": len(answers),
        "total_clashes": len(clash_groups),
        "the_me_gameover": state.get("the_me_gameover", False),
        "the_me_winner": state.get("the_me_winner"),
        "winner_reason": state.get("winner_reason"),
        "alive_survivor_count": len(
            [
                p
                for pid, p in players.items()
                if pid != the_me_id and not p.get("is_spectator") and not p.get("eliminated")
            ]
        ),
        "timestamp": time.time(),
    }
    state["round_results"] = round_summary
    state.setdefault("round_history", []).append(round_summary)

    # Log summary
    if clash_groups:
        clash_msg = f"💥 {len(clash_groups)} collision(s) detected!"
    else:
        clash_msg = "✨ No collisions this round!"
    append_event(state, "System", f"Round {state.get('round_num', 1)} results: {clash_msg}")

    save_game(state["code"], state)
    return round_summary


def toggle_answer_validity(state: dict[str, Any], player_id: str, is_valid: bool) -> bool:
    """Host arbitration: override validity of a player's answer during reveal phase."""
    if state.get("phase") not in ("reveal", "recap"):
        return False
    rr = state.get("round_results")
    if not rr:
        return False

    p_res = rr.get("player_results", {}).get(player_id)
    if not p_res:
        return False

    old_pts = p_res.get("points_awarded", 0)
    p_res["is_valid"] = is_valid
    is_clash = (
        p_res.get("status") == "clash"
        or len(
            [
                x
                for x in rr.get("player_results", {}).values()
                if x.get("clean_key") == p_res.get("clean_key") and x["player_id"] != player_id
            ]
        )
        > 0
    )

    settings = state.get("settings", DEFAULT_SETTINGS)
    collision_mode = settings.get("collision_mode", "classic")

    if not is_valid:
        new_pts = 0
        p_res["status"] = "invalid"
    elif is_clash:
        new_pts = -50 if collision_mode == "harsh" else 0
        p_res["status"] = "clash"
    else:
        new_pts = 150 if p_res.get("is_obscure") else 100
        p_res["status"] = "unique"

    diff = new_pts - old_pts
    p_res["points_awarded"] = new_pts
    player = state.get("players", {}).get(player_id)
    if player:
        player["score"] = max(0, player.get("score", 0) + diff)
        p_res["total_score"] = player["score"]

    append_event(
        state, "Host", f"⚖️ Host marked {p_res['player_name']}'s answer as {'Valid ✅' if is_valid else 'Invalid ❌'}."
    )
    save_game(state["code"], state)
    return True


def adjudicate_oral_round(
    state: dict[str, Any],
    verdicts: dict[str, Any],
) -> dict[str, Any]:
    """Host adjudicates results for oral living-room round."""
    settings = state.get("settings", DEFAULT_SETTINGS)
    collision_mode = settings.get("collision_mode", "classic")
    prompt = state.get("current_prompt") or {}
    players = state.get("players", {})

    state["phase"] = "reveal"
    player_results: dict[str, Any] = {}
    clash_groups: list[dict[str, Any]] = []

    for pid, p in players.items():
        if p.get("is_spectator"):
            continue
        v_info = verdicts.get(pid, {})
        status = v_info.get("status", "valid")
        ans_text = (v_info.get("answer") or "").strip()

        if status == "invalid":
            pts = 0
            is_valid = False
            is_obs = False
        elif status == "clash":
            pts = -50 if collision_mode == "harsh" else 0
            is_valid = True
            is_obs = False
        elif status == "obscure":
            pts = 150
            is_valid = True
            is_obs = True
        else:  # "valid" / "unique"
            pts = 100
            is_valid = True
            is_obs = False
            status = "unique"

        p["score"] = max(0, p.get("score", 0) + pts)
        state.setdefault("round_answers", {})[pid] = {
            "raw": ans_text,
            "submitted_at": time.time(),
        }
        player_results[pid] = {
            "player_id": pid,
            "player_name": p["name"],
            "raw_answer": ans_text,
            "clean_key": clean_answer_key(ans_text),
            "status": status,
            "is_valid": is_valid,
            "is_obscure": is_obs,
            "points_awarded": pts,
            "total_score": p["score"],
            "reason": "Living Room Oral Table verdict",
        }

    round_summary = {
        "round_num": state.get("round_num", 1),
        "prompt": prompt,
        "player_results": player_results,
        "clash_groups": clash_groups,
        "total_submissions": len(player_results),
        "total_clashes": sum(1 for r in player_results.values() if r["status"] == "clash"),
        "timestamp": time.time(),
    }
    state["round_results"] = round_summary
    state.setdefault("round_history", []).append(round_summary)
    append_event(state, "Host", f"🗣️ Oral round {state.get('round_num', 1)} results finalized!")
    save_game(state["code"], state)
    return round_summary


def toggle_answer_clash(state: dict[str, Any], player_id: str) -> bool:
    """Host arbitration: toggle whether an answer is forced into a clash or forced unique."""
    if state.get("phase") not in ("reveal", "recap"):
        return False
    rr = state.get("round_results")
    if not rr:
        return False
    p_res = rr.get("player_results", {}).get(player_id)
    if not p_res:
        return False

    old_pts = p_res.get("points_awarded", 0)
    old_status = p_res.get("status")

    settings = state.get("settings", DEFAULT_SETTINGS)
    collision_mode = settings.get("collision_mode", "classic")

    if old_status in ("clash", "caught_by_me"):
        # Un-clash: make unique
        new_status = "unique"
        new_pts = 100
        p_res["eliminated"] = False
        p_res["reason"] = "Host marked as unique answer."
    else:
        # Force clash
        new_status = "clash"
        new_pts = -50 if collision_mode == "harsh" else 0
        p_res["reason"] = "Host marked as duplicate / collision."

    diff = new_pts - old_pts
    p_res["status"] = new_status
    p_res["points_awarded"] = new_pts
    player = state.get("players", {}).get(player_id)
    if player:
        player["score"] = max(0, player.get("score", 0) + diff)
        p_res["total_score"] = player["score"]
        if new_status == "clash" and settings.get("game_mode") == "the_me":
            player["eliminated"] = True
            p_res["eliminated"] = True

    append_event(state, "Host", f"⚖️ Host marked {p_res['player_name']}'s answer as {new_status.upper()}.")
    save_game(state["code"], state)
    return True


def end_game(state: dict[str, Any], by_name: str = "Host") -> bool:
    """Manually end the game and move directly to gameover podium."""
    state["phase"] = "gameover"
    if not state.get("winner_reason"):
        state["winner_reason"] = f"🏁 Match concluded by {by_name}!"
    append_event(state, "System", f"🏁 Match concluded by {by_name}!")
    save_game(state["code"], state)
    return True


def advance_next_round(state: dict[str, Any]) -> bool:
    """Advance from reveal to next round, or game over if max rounds reached or The ME eliminated players."""
    max_rounds = int(state.get("settings", {}).get("max_rounds", 6))
    cur_round = int(state.get("round_num", 1))

    should_end = max_rounds > 0 and cur_round >= max_rounds
    if state.get("the_me_gameover") or should_end:
        state["phase"] = "gameover"
        append_event(state, "System", "🏆 Game Over! Check the final podium!")
        save_game(state["code"], state)
        return True

    state["round_num"] = cur_round + 1
    return setup_round(state)


def reset_game(state: dict[str, Any]) -> None:
    """Reset room back to lobby for a fresh match."""
    state["phase"] = "lobby"
    state["round_num"] = 0
    state["current_prompt"] = None
    state["round_answers"] = {}
    state["round_results"] = None
    state["round_history"] = []
    state["used_prompt_ids"] = []
    state["the_me_gameover"] = False
    state["the_me_winner"] = None
    state["winner_reason"] = None
    state["winner_id"] = None
    for p in state.get("players", {}).values():
        p["score"] = 0
        p["eliminated"] = False
        p.pop("eliminated_round", None)
    append_event(state, "System", "🔄 Room reset to lobby. Ready for a new game!")
    save_game(state["code"], state)


def get_sanitized_player_view(state: dict[str, Any], viewer: Optional[str] = None) -> dict[str, Any]:
    """
    Construct client view with zero-spoiler guarantees:
    - During 'answering' phase: viewer can see their own submitted answer, but NEVER other players' answers!
      Other players are shown only as `has_submitted: bool`.
    - Only during 'reveal', 'recap', or 'gameover' are all answers exposed.
    """
    view = copy.deepcopy(state)
    phase = view.get("phase", "lobby")
    round_answers = view.pop("round_answers", {})
    viewer_record = find_player_by_token(view, viewer) or view.get("players", {}).get(viewer)
    viewer_id = viewer_record["id"] if viewer_record else None
    viewer_token = viewer_record.get("token") if viewer_record else None
    viewer_is_admin = is_player_admin(view, viewer_record)

    the_me_id = view.get("the_me_player_id")
    the_me_p = view.get("players", {}).get(the_me_id) if isinstance(view.get("players"), dict) else None
    the_me_name = the_me_p["name"] if the_me_p else None
    the_me_ans = view.get("the_me_answer")

    # Sanitize players list
    sanitized_players = []
    for pid, p in view.get("players", {}).items():
        p_copy = copy.deepcopy(p)
        # Strip private secret token unless it's the viewer's own record
        if p_copy.get("token") != viewer_token:
            p_copy.pop("token", None)
        p_copy.pop("channel_name", None)
        p_copy["is_the_me"] = bool(pid == the_me_id)

        # Indicate submission status without revealing content
        ans_info = round_answers.get(pid)
        p_copy["has_submitted"] = bool(ans_info and ans_info.get("raw") is not None)

        if phase in ("the_me_answering", "answering"):
            if pid == viewer_id:
                p_copy["my_answer"] = ans_info.get("raw", "") if ans_info else ""
        elif phase in ("reveal", "recap", "gameover"):
            p_copy["revealed_answer"] = ans_info.get("raw", "") if ans_info else ""

        sanitized_players.append(p_copy)

    sanitized_players.sort(key=lambda x: x.get("score", 0), reverse=True)
    view["players"] = sanitized_players

    # Zero-spoiler guarantee for 'The ME' answer
    if phase in ("the_me_answering", "answering"):
        if viewer_id == the_me_id:
            view["my_answer"] = the_me_ans.get("raw", "") if the_me_ans else ""
        else:
            view["my_answer"] = round_answers.get(viewer_id, {}).get("raw", "") if viewer_id else ""
        view["the_me_answer"] = None  # Hide forbidden word from other players!
    else:
        view["all_answers"] = {pid: info.get("raw", "") for pid, info in round_answers.items()}

    view["the_me_has_submitted"] = bool(the_me_ans and the_me_ans.get("raw"))
    view["the_me_player_name"] = the_me_name

    view["viewer"] = {
        "id": viewer_id,
        "name": viewer_record["name"] if viewer_record else None,
        "is_admin": viewer_is_admin,
        "is_the_me": bool(viewer_id and viewer_id == the_me_id),
        "is_spectator": viewer_record.get("is_spectator", False) if viewer_record else False,
    }

    # Available prompt packs metadata for host lobby
    view["available_packs"] = [{"id": pid, "label": label} for pid, label in PACK_CHOICES]
    view["available_game_modes"] = [{"id": gid, "label": glbl} for gid, glbl in GAME_MODES]
    view["available_the_me_rotations"] = [{"id": rid, "label": rlbl} for rid, rlbl in THE_ME_ROTATIONS]
    view["collision_modes"] = list(COLLISION_MODES)
    view["pacing_modes"] = list(PACING_MODES)

    return view
