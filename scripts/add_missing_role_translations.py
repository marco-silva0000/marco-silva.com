def main():
    target_file = Path(__file__).resolve().parent.parent / "lupus" / "translations.py"
    content = target_file.read_text(encoding="utf-8")

    # Format the additional roles into valid Python dict code

    formatted_roles = []
    for role_id, translations in ADDITIONAL_ROLES.items():
        role_repr = f"    {repr(role_id)}: {{\n"
        for lang, fields in translations.items():
            role_repr += f"        {repr(lang)}: {{\n"
            for k, v in fields.items():
                role_repr += f"            {repr(k)}: {repr(v)},\n"
            role_repr += "        },\n"
        role_repr += "    },"
        formatted_roles.append(role_repr)

    roles_code = "\n" + "\n".join(formatted_roles) + "\n"

    # We need to insert before FACTION_TRANSLATIONS
    marker = "FACTION_TRANSLATIONS: dict[str, dict[str, str]] = {"
    if marker not in content:
        print("Marker FACTION_TRANSLATIONS not found!")
        sys.exit(1)

    parts = content.split(marker)
    # The last closing brace before marker is the end of ROLE_TRANSLATIONS
    last_brace_idx = parts[0].rfind("}")
    new_first_part = parts[0][:last_brace_idx] + roles_code + parts[0][last_brace_idx:]
    new_content = new_first_part + marker + parts[1]

    target_file.write_text(new_content, encoding="utf-8")
    print(f"Successfully added {len(ADDITIONAL_ROLES)} roles to {target_file}")


if __name__ == "__main__":
    main()
